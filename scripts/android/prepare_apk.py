#!/usr/bin/env python3
"""Assemble the Android build folder (everything Buildozer needs) and its spec.

Layout produced in ``--build-dir`` (default ``android/build/app``, git-ignored)::

    main.py                 the p4a entry point
    easywalp/               the shared core, copied from src/easywalp (no PySide6 UI)
    easywalp_android/       the Kivy app package
    assets/fonts|icons|logo|i18n   bundled resources (fonts + translations)
    assets/photocraft/      the engine's licence files (attribution)
    libs/<abi>/libphotocraft_cli.so    the cross-compiled engine
    buildozer.spec          generated from android/buildozer.spec

Usage::

    python scripts/android/prepare_apk.py --version 1.0.0 --engine-dir engines-android \\
        --sdk "$ANDROID_HOME" --ndk "$ANDROID_NDK_LATEST_HOME" --build-dir android/build/app

``--engine-dir`` is searched recursively for ``<abi>/libphotocraft_cli.so``; the
ABIs to ship come from ``--abis`` (default: arm64-v8a, x86 - the same list as
``android/buildozer.spec``).
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANDROID_DIR = ROOT / "android"
CORE_PACKAGE = ROOT / "src" / "easywalp"
DEFAULT_ABIS = ("arm64-v8a", "x86")
#: sub-packages of the core that only exist for the desktop GUI
CORE_SKIP = {"app", "__pycache__"}
#: ABIs buildozer 1.6 can attach extra native libraries to (`android.add_libs_*`)
BUILDOZER_ABIS = {"armeabi", "armeabi-v7a", "arm64-v8a", "x86", "mips"}
LIB_KEY = {"armeabi": "armeabi", "armeabi-v7a": "armeabi_v7a", "arm64-v8a": "arm64_v8a",
           "x86": "x86", "x86_64": "x86_64", "mips": "mips"}
LICENCE_FILES = ("LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "ATTRIBUTION.md")


class PrepareError(RuntimeError):
    """A readable preparation failure."""


def copy_core(dest: Path) -> int:
    """Copy the shared ``easywalp`` package minus the PySide6 GUI."""
    target = dest / "easywalp"
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True)
    count = 0
    for source in sorted(CORE_PACKAGE.iterdir()):
        if source.name in CORE_SKIP or source.suffix == ".pyc":
            continue
        if source.is_dir():
            continue  # only easywalp.app is a directory and it is skipped above
        shutil.copy2(source, target / source.name)
        count += 1
    (target / "_build_version.py").unlink(missing_ok=True)
    return count


def copy_app_package(dest: Path) -> int:
    target = dest / "easywalp_android"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(
        ANDROID_DIR / "easywalp_android",
        target,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    return len(list(target.rglob("*.py")))


def copy_resources(dest: Path, engine_dir: Path | None) -> None:
    """Fonts, icons, translations and the engine's licence files."""
    assets = dest / "assets"
    for name in ("fonts", "icons", "logo"):
        source = ROOT / "assets" / name
        if source.is_dir():
            shutil.copytree(source, assets / name, dirs_exist_ok=True)
    (assets / "i18n").mkdir(parents=True, exist_ok=True)
    for table in sorted((ROOT / "i18n").glob("*.json")):
        shutil.copy2(table, assets / "i18n" / table.name)
    photocraft = assets / "photocraft"
    photocraft.mkdir(parents=True, exist_ok=True)
    sources = [ROOT / "assets" / "photocraft"]
    if engine_dir is not None:
        sources.append(engine_dir)
    for source in sources:
        for name in LICENCE_FILES:
            candidate = source / name
            if candidate.is_file():
                shutil.copy2(candidate, photocraft / name)


def copy_engine(engine_dir: Path, dest: Path, abis: tuple[str, ...]) -> list[Path]:
    """Place ``<abi>/libphotocraft_cli.so`` into the build folder's ``libs/``."""
    placed: list[Path] = []
    for abi in abis:
        matches = sorted(engine_dir.rglob(f"{abi}/libphotocraft_cli.so"))
        if not matches:
            matches = sorted(engine_dir.rglob(f"{abi}/photocraft-cli"))
        if not matches:
            raise PrepareError(f"no engine binary for {abi} under {engine_dir}")
        target = dest / "libs" / abi / "libphotocraft_cli.so"
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(matches[0], target)
        target.chmod(0o755)
        placed.append(target)
    return placed


def write_version(core_dir: Path, version: str) -> None:
    (core_dir / "easywalp" / "_build_version.py").write_text(
        '"""Generated by scripts/android/prepare_apk.py - do not edit, do not commit."""\n'
        f'BUILD_VERSION = "{version}"\n',
        encoding="utf-8",
    )


def numeric_version(version: str) -> int:
    """`0.1.0` -> 100, `1.2.3` -> 10203: monotonic enough for Android's versionCode."""
    parts = [int(p) for p in re.findall(r"\d+", version)[:3]] or [0]
    while len(parts) < 3:
        parts.append(0)
    major, minor, patch = (min(p, 9999) for p in parts)
    return major * 10000 + minor * 100 + patch


def render_spec(dest: Path, version: str, sdk: str | None, ndk: str | None,
                p4a_dir: str | None, abis: tuple[str, ...] = ()) -> Path:
    """Copy android/buildozer.spec into the build folder with the values filled in."""
    spec = (ANDROID_DIR / "buildozer.spec").read_text(encoding="utf-8")
    spec = re.sub(r"(?m)^version = .*$", f"version = {version}", spec)
    if abis:
        spec = re.sub(r"(?m)^android\.archs = .*$", "android.archs = " + ",".join(abis), spec)
    extra: list[str] = [f"android.numeric_version = {numeric_version(version)}"]
    for abi in abis:
        if abi in BUILDOZER_ABIS:
            extra.append(f"android.add_libs_{LIB_KEY[abi]} = libs/{abi}/*.so")
        else:
            print(f"warning: buildozer cannot attach native libraries for {abi}; "
                  f"the engine will not be bundled for it", file=sys.stderr)
    if sdk:
        extra.append(f"android.sdk_path = {sdk}")
    if ndk:
        extra.append(f"android.ndk_path = {ndk}")
    if p4a_dir:
        # Pin python-for-android to a checkout (reproducible builds; CI clones the tag).
        extra.append(f"p4a.source_dir = {p4a_dir}")
    if extra:
        spec = spec.rstrip() + "\n\n# --- filled in by scripts/android/prepare_apk.py ---\n" + "\n".join(extra) + "\n"
    target = dest / "buildozer.spec"
    target.write_text(spec, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Prepare the EasyWalp Android build folder")
    parser.add_argument("--version", required=True, help="version to stamp, e.g. 1.0.0")
    parser.add_argument("--engine-dir", type=Path, default=None,
                        help="folder with <abi>/libphotocraft_cli.so (or --skip-engine)")
    parser.add_argument("--skip-engine", action="store_true",
                        help="build an APK without the engine (UI-only)")
    parser.add_argument("--abis", default=",".join(DEFAULT_ABIS),
                        help=f"comma-separated ABIs (default: {','.join(DEFAULT_ABIS)}); "
                             f"buildozer attaches engine libraries for {','.join(sorted(BUILDOZER_ABIS))}")
    parser.add_argument("--sdk", default=None, help="Android SDK path (written into the spec)")
    parser.add_argument("--ndk", default=None, help="Android NDK path (written into the spec)")
    parser.add_argument("--p4a-dir", default=None, help="python-for-android checkout to use")
    parser.add_argument("--build-dir", type=Path, default=ANDROID_DIR / "build" / "app")
    args = parser.parse_args(argv)

    version = args.version.strip().lstrip("vV")
    if not version:
        print("error: --version is empty", file=sys.stderr)
        return 2
    abis = tuple(a.strip() for a in args.abis.split(",") if a.strip())
    dest = args.build_dir
    dest.mkdir(parents=True, exist_ok=True)

    shutil.copy2(ANDROID_DIR / "main.py", dest / "main.py")
    files = copy_core(dest)
    modules = copy_app_package(dest)
    copy_resources(dest, args.engine_dir)
    write_version(dest, version)
    spec = render_spec(dest, version, args.sdk, args.ndk, args.p4a_dir, abis)

    placed: list[Path] = []
    if not args.skip_engine:
        if args.engine_dir is None:
            print("error: --engine-dir is required unless --skip-engine is used", file=sys.stderr)
            return 2
        if not args.engine_dir.exists():
            print(f"error: engine folder not found: {args.engine_dir}", file=sys.stderr)
            return 2
        try:
            placed = copy_engine(args.engine_dir, dest, abis)
        except PrepareError as e:
            print(f"error: {e}", file=sys.stderr)
            return 1

    print(f"build folder: {dest}")
    print(f"  easywalp core files: {files}")
    print(f"  easywalp_android modules: {modules}")
    for path in placed:
        print(f"  engine: {path.relative_to(dest)} ({path.stat().st_size / 1e6:.1f} MB)")
    print(f"  spec: {spec}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
