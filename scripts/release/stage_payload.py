#!/usr/bin/env python3
"""Stage everything the Windows build needs, before PyInstaller runs.

Two jobs:

1. **Stamp the version** - write ``src/easywalp/_build_version.py`` (git-ignored)
   so ``easywalp.__version__`` matches the release being built.
2. **Stage the engine** - copy ``photocraft-cli.exe`` plus its license/NOTICE
   files from the CI artefact folder into ``<dest>/photocraft``. The PyInstaller
   spec picks that folder up and ships it as ``assets/photocraft`` inside the
   app, where ``easywalp.paths.bundled_dir()`` finds it.

Usage (CI):

    python scripts/release/stage_payload.py \
        --version 1.0.0 --engine-dir build-staging --dest build/payload
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENGINE_FILES = ("photocraft-cli.exe", "photocraft-cli")
LICENSE_FILES = ("LICENSE-MIT", "LICENSE-APACHE", "NOTICE", "ATTRIBUTION.md")


class StagingError(RuntimeError):
    """A readable staging failure (a missing artefact, usually)."""


def write_build_version(version: str) -> Path:
    """Stamp the version into the package (``src/easywalp/_build_version.py``)."""
    target = ROOT / "src" / "easywalp" / "_build_version.py"
    target.write_text(
        '"""Generated by scripts/release/stage_payload.py - do not edit, do not commit."""\n'
        f'BUILD_VERSION = "{version}"\n',
        encoding="utf-8",
    )
    return target


def find_engine(engine_dir: Path, binary: str | None = None) -> Path:
    """Locate the engine binary in an artefact folder (recursively)."""
    names = [binary] if binary else list(ENGINE_FILES)
    for name in names:
        hit = engine_dir / name
        if hit.is_file():
            return hit
    for name in names:
        for hit in sorted(engine_dir.rglob(name)):
            if hit.is_file():
                return hit
    raise StagingError(
        f"no photocraft-cli binary ({', '.join(n for n in names if n)}) under {engine_dir}"
    )


def stage_engine(engine_dir: Path, dest: Path, binary: str | None = None) -> list[Path]:
    """Copy the engine + its licenses into ``<dest>/photocraft``."""
    engine = find_engine(engine_dir, binary)
    out_dir = dest / "photocraft"
    out_dir.mkdir(parents=True, exist_ok=True)
    written = [shutil.copy2(engine, out_dir / engine.name)]
    for name in LICENSE_FILES:
        src = engine_dir / name
        if not src.is_file():
            continue
        written.append(shutil.copy2(src, out_dir / name))
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Stage the EasyWalp release payload")
    parser.add_argument("--version", required=True, help="version to stamp, e.g. 1.0.0")
    parser.add_argument("--engine-dir", type=Path, default=None,
                        help="folder holding the built photocraft-cli (recursively searched)")
    parser.add_argument("--engine-binary", default=None,
                        help="exact file name to look for (default: platform names)")
    parser.add_argument("--dest", type=Path, default=ROOT / "build" / "payload",
                        help="payload folder (default: build/payload)")
    parser.add_argument("--skip-engine", action="store_true",
                        help="only stamp the version (no engine staged)")
    args = parser.parse_args(argv)

    version = args.version.strip().lstrip("vV")
    if not version:
        print("error: --version is empty", file=sys.stderr)
        return 2

    stamped = write_build_version(version)
    print(f"version stamped: {stamped} -> {version}")

    if args.skip_engine:
        return 0
    if args.engine_dir is None:
        print("error: --engine-dir is required unless --skip-engine is used", file=sys.stderr)
        return 2
    if not args.engine_dir.exists():
        print(f"error: engine folder not found: {args.engine_dir}", file=sys.stderr)
        return 2

    try:
        written = stage_engine(args.engine_dir, args.dest, args.engine_binary)
    except StagingError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    for path in written:
        print(f"staged: {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
